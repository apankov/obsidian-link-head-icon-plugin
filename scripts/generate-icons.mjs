// Writes src/icons.generated.ts: only the SVG path and brand color of each
// icon the plugin uses. Bundling simple-icons entries directly also ships
// their full SVG markup and metadata, which roughly doubles main.js.
//
// Paths are rounded to 0.1 of the 24-unit viewBox: invisible at 16 px, and
// it shrinks detailed icons (Habr's path drops from 16 KB to under 6 KB).
//
// Run `npm run icons` after changing the list below.
import { writeFileSync } from "node:fs";
import { optimize } from "svgo";
import * as current from "simple-icons";
// Icons removed from current simple-icons releases.
import * as legacy from "simple-icons-legacy";

/** Icon id → [simple-icons package, export name]. */
const ICONS = {
	"asana": [current, "siAsana"],
	"chatgpt": [legacy, "siOpenai"],
	"claude": [current, "siClaude"],
	"clickup": [current, "siClickup"],
	"facebook": [current, "siFacebook"],
	"github": [current, "siGithub"],
	"gitlab": [current, "siGitlab"],
	"google-docs": [current, "siGoogledocs"],
	"google-drive": [current, "siGoogledrive"],
	"google-forms": [current, "siGoogleforms"],
	"google-sheets": [current, "siGooglesheets"],
	"google-slides": [current, "siGoogleslides"],
	"habr": [current, "siHabr"],
	"instagram": [current, "siInstagram"],
	"linkedin": [legacy, "siLinkedin"],
	"medium": [current, "siMedium"],
	"microsoft-teams": [legacy, "siMicrosoftteams"],
	"miro": [current, "siMiro"],
	"npm": [current, "siNpm"],
	"slack": [legacy, "siSlack"],
	"stackoverflow": [current, "siStackoverflow"],
	"telegram": [current, "siTelegram"],
	"twitter": [legacy, "siTwitter"],
	"wikipedia": [current, "siWikipedia"],
	"x": [current, "siX"],
	"youtube": [current, "siYoutube"],
};

function simplify(svg) {
	const { data } = optimize(svg, { floatPrecision: 1 });
	const paths = [...data.matchAll(/<path d="([^"]+)"/g)];
	if (paths.length !== 1) {
		throw new Error(`expected one path after svgo, got ${paths.length}`);
	}
	return paths[0][1];
}

const entries = Object.entries(ICONS).map(([id, [pkg, name]]) => {
	const icon = pkg[name];
	if (!icon) {
		throw new Error(`simple-icons has no export ${name}`);
	}
	return `\t${JSON.stringify(id)}: { hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(simplify(icon.svg))} },`;
});

writeFileSync(
	"src/icons.generated.ts",
	`// Generated by scripts/generate-icons.mjs from simple-icons (CC0). Do not edit.
export const ICONS = {
${entries.join("\n")}
} as const;
`,
);
